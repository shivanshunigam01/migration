import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const routerSrc = fs.readFileSync(path.join(root, "src/app/router.tsx"), "utf8")
const routesSrc = fs.readFileSync(path.join(root, "src/data/routes.ts"), "utf8")

const ROUTE = {}
for (const m of routesSrc.matchAll(/^\s+(\w+):\s+'([^']+)'/gm)) {
  ROUTE[m[1]] = m[2]
}

/** @type {Map<string, string>} path -> import specifier */
const pathImports = new Map()

// Standard: const NameLazy = lazy(() => import("mod"))
const lazyMod = new Map()
for (const m of routerSrc.matchAll(/const (\w+)Lazy = lazy\(\(\) => import\("([^"]+)"\)\)/g)) {
  lazyMod.set(m[1].replace(/Lazy$/, ""), m[2])
}
// withNavigate name
const wrapName = new Map()
for (const m of routerSrc.matchAll(/const (\w+) = withNavigate\((\w+)Lazy/g)) {
  wrapName.set(m[1], m[2].replace(/Lazy$/, ""))
}

// Pages key -> component variable name
const pagesKeyToComp = new Map()
const pagesBlock = routerSrc.match(/const Pages = \{([\s\S]*?)\} as const/)
for (const m of pagesBlock[1].matchAll(/(\w+):\s*(\w+)/g)) {
  pagesKeyToComp.set(m[1], m[2])
}

function addPath(routePath, pagesKey) {
  const clean = routePath.replace(/^\//, "")
  if (clean.includes(":")) return
  const comp = pagesKeyToComp.get(pagesKey)
  if (!comp) return
  pathImports.set(clean, comp)
}

for (const m of routerSrc.matchAll(/path="(\/[^"]+)"\s+element=\{<Pages\.(\w+)/g)) {
  addPath(m[1], m[2])
}
for (const m of routerSrc.matchAll(/path=\{\`\/\$\{ROUTE\.(\w+)\}\`\}\s+element=\{<Pages\.(\w+)/g)) {
  const p = ROUTE[m[1]]
  if (p) addPath("/" + p, m[2])
}

// Resolve component -> module
function moduleFor(compName) {
  if (compName === "HomePage") return "@/views/HomePage"
  // Legal specials
  if (compName === "PrivacyPage") return "@/views/LegalPage"
  if (compName === "TermsPage") return "@/views/LegalPage"
  if (compName === "AccessibilityPage") return "@/views/LegalPage"
  const base = wrapName.get(compName) || compName.replace(/Page$/, "")
  // try lazyMod by wrapped base name
  for (const [wrapped, baseName] of wrapName) {
    if (wrapped === compName) {
      const mod = [...lazyMod.entries()].find(([k]) => k === baseName || wrapped.startsWith(k))
      // lazyMod keys are without Lazy suffix from NameLazy -> Name
      const key = wrapName.get(compName)
      // wrapName: EmployerSponsorshipPage -> EmployerSponsorshipPage (from EmployerSponsorshipPageLazy)
      const lazyKey = compName // const X = withNavigate(XLazy -> X maps to X
    }
  }
  // Direct: const FooPage = withNavigate(FooPageLazy) and FooPageLazy import
  const fromLazy = lazyMod.get(compName)
  if (fromLazy) return fromLazy
  // try without Page suffix issues - scan original for this component
  const re = new RegExp(`const ${compName}Lazy = lazy\\(\\(\\) => import\\("([^"]+)"\\)`)
  const hit = routerSrc.match(re)
  if (hit) return hit[1]
  const re2 = new RegExp(`const ${compName} = withNavigate\\((\\w+)Lazy`)
  const hit2 = routerSrc.match(re2)
  if (hit2) {
    const re3 = new RegExp(`const ${hit2[1]}Lazy = lazy\\(\\(\\) => import\\("([^"]+)"\\)`)
    const hit3 = routerSrc.match(re3)
    if (hit3) return hit3[1]
  }
  return null
}

const lines = []
lines.push(`"use client"`)
lines.push(``)
lines.push(`/** Auto-generated by scripts/gen-next-page-registry.mjs — do not edit by hand. */`)
lines.push(`import type { ComponentType } from "react"`)
lines.push(`import dynamic from "next/dynamic"`)
lines.push(`import { withNavigate } from "@/lib/withNavigate"`)
lines.push(`import HomePage from "@/views/HomePage"`)
lines.push(`import LegalPage from "@/views/LegalPage"`)
lines.push(``)

const uniqueMods = new Map() // compName -> mod
for (const comp of new Set(pathImports.values())) {
  if (comp === "HomePage" || comp === "PrivacyPage" || comp === "TermsPage" || comp === "AccessibilityPage") continue
  const mod = moduleFor(comp)
  if (!mod) {
    console.warn("No module for", comp)
    continue
  }
  uniqueMods.set(comp, mod)
}

for (const [comp, mod] of [...uniqueMods.entries()].sort((a, b) => a[0].localeCompare(b[0]))) {
  lines.push(`import ${comp}Raw from "${mod}"`)
}

lines.push(``)
for (const comp of [...uniqueMods.keys()].sort()) {
  lines.push(`const ${comp} = withNavigate(${comp}Raw as never)`)
}

lines.push(`const Home = withNavigate(HomePage as never)`)
lines.push(`const Privacy = withNavigate(function Privacy(p: { navigate: (page: string) => void }) { return <LegalPage kind="privacy" navigate={p.navigate} /> } as never)`)
lines.push(`const Terms = withNavigate(function Terms(p: { navigate: (page: string) => void }) { return <LegalPage kind="terms" navigate={p.navigate} /> } as never)`)
lines.push(`const Accessibility = withNavigate(function Accessibility(p: { navigate: (page: string) => void }) { return <LegalPage kind="accessibility" navigate={p.navigate} /> } as never)`)
lines.push(``)
lines.push(`export type AppPageComponent = ComponentType`)
lines.push(``)
lines.push(`export const PAGE_REGISTRY: Record<string, AppPageComponent> = {`)
lines.push(`  "": Home,`)

const legalMap = {
  PrivacyPage: "Privacy",
  TermsPage: "Terms",
  AccessibilityPage: "Accessibility",
  HomePage: "Home",
}

for (const [p, comp] of [...pathImports.entries()].sort((a, b) => a[0].localeCompare(b[0]))) {
  const exportName = legalMap[comp] || comp
  if (comp === "HomePage") continue
  if (!uniqueMods.has(comp) && !legalMap[comp]) {
    console.warn("Skipping unmapped", p, comp)
    continue
  }
  lines.push(`  ${JSON.stringify(p)}: ${exportName},`)
}
lines.push(`}`)
lines.push(``)
lines.push(`export function getRegistryPage(slugPath: string): AppPageComponent | null {`)
lines.push(`  const key = slugPath.replace(/^\\/+|\\/+$/g, "")`)
lines.push(`  return PAGE_REGISTRY[key] ?? null`)
lines.push(`}`)
lines.push(``)
lines.push(`export const REGISTRY_PATHS = Object.keys(PAGE_REGISTRY).filter(Boolean)`)
lines.push(``)

const out = path.join(root, "src/next/pageRegistry.tsx")
fs.mkdirSync(path.dirname(out), { recursive: true })
fs.writeFileSync(out, lines.join("\n"))
console.log("Wrote", out)
console.log("paths", pathImports.size, "modules", uniqueMods.size)
